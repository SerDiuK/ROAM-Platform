import { z } from "zod";

// --- Responder Availability ---
// `available`  — ready to be checked in to a vehicle / accept dispatches.
// `occupied`   — currently assigned to an active dispatch (claimed but not
//                yet cleared). Set by dispatch.respond, cleared by
//                dispatch.clear. Going on shift no longer flips this — a
//                responder on shift but idle stays `available`.
// `off_duty`   — not on shift; should not appear in assignment UIs.
// `unavailable`— temporarily blocked (leave, medical, admin hold).
export const RESPONDER_AVAILABILITIES = [
	"available",
	"occupied",
	"off_duty",
	"unavailable",
] as const;
export const ResponderAvailabilitySchema = z.enum(RESPONDER_AVAILABILITIES);
export type ResponderAvailability = z.infer<typeof ResponderAvailabilitySchema>;

// --- Responder Capability ---
// Operational specializations the agent uses to match responders to incidents.
// Fleet is ambulance-only for now, so the only capability is `medic`.
export const RESPONDER_CAPABILITIES = ["medic"] as const;
export const ResponderCapabilitySchema = z.enum(RESPONDER_CAPABILITIES);
export type ResponderCapability = z.infer<typeof ResponderCapabilitySchema>;

// --- Responder ---
// Identity-only; physical verification at checkin is handled client-side
// (proximity + long-press confirmation in the mobile app).
// `name` is the login handle — kept short so it's easy to type on a mobile
// number-pad-adjacent keyboard. `displayName` is the human-readable full name
// shown in dashboards and on the responder's own mobile profile; it never
// participates in auth lookups.
// `walletAddress` is the responder's Solana address (Crossmint-managed embedded
// wallet); populated on first sign-in. `pushTokens` are Expo push tokens —
// list because a responder may have multiple devices.
// `currentVehicleId` is the persistent responder↔vehicle pairing — set by
// auth.checkin, cleared by auth.checkout. Replaces the off-chain Session
// collection (AD-22). A unique-sparse Mongo index enforces 1 responder per
// vehicle automatically.
export const ResponderSchema = z.object({
	_id: z.string(), // UUID with dashes — generated by randomUUID() at enrol time
	name: z.string(),
	displayName: z.string().optional(),
	role: z.enum(["responder", "dispatcher"]),
	availability: ResponderAvailabilitySchema,
	capabilities: z.array(ResponderCapabilitySchema).optional(),
	pushTokens: z.array(z.string()).optional(),
	walletAddress: z.string().optional(),
	currentVehicleId: z.string().nullable().optional(),
});
export type Responder = z.infer<typeof ResponderSchema>;

// --- Enrol Request ---
export const EnrolRequestSchema = z.object({
	name: z.string(),
	role: z.enum(["responder", "dispatcher"]),
	availability: ResponderAvailabilitySchema,
});
export type EnrolRequest = z.infer<typeof EnrolRequestSchema>;

// --- Push token registration ---
// Posted by the mobile app once it has been granted notification permission and
// fetched its Expo push token. Backend appends to responder.pushTokens (de-duped).
// The owning responder is derived from the auth context — the device cannot
// register a token against a different responder than the one it is signed in as.
export const UpsertPushTokenRequestSchema = z.object({
	token: z.string().min(1),
});
export type UpsertPushTokenRequest = z.infer<
	typeof UpsertPushTokenRequestSchema
>;

// --- Session sign-in ---
// Responder types their name + PIN. Backend verifies pinHash, returns a
// JWT plus the responder object. Mobile + dashboard cache the token in their
// platform's secure storage.
export const SignInRequestSchema = z.object({
	name: z.string().min(1),
	pin: z.string().min(4).max(12),
});
export type SignInRequest = z.infer<typeof SignInRequestSchema>;

export const SignInResponseSchema = z.object({
	token: z.string(),
	responder: ResponderSchema,
});
export type SignInResponse = z.infer<typeof SignInResponseSchema>;

// --- Current-session check ---
// Mobile calls this on cold boot with the cached token; if it succeeds the app
// drops straight into the map, otherwise it routes to the login screen.
export const MeResponseSchema = z.object({
	responder: ResponderSchema,
});
export type MeResponse = z.infer<typeof MeResponseSchema>;

// --- Checkin / Checkout ---
// Checkin pairs a responder to a vehicle for their shift. The responder is
// identified by name; verification (proximity + long-press confirmation) is
// enforced client-side in the mobile app before this request is sent.
// Checkout takes only a vehicle id — the active responder is whoever has
// `currentVehicleId === vehicleId`.
export const CheckinRequestSchema = z.object({
	vehicleId: z.string(),
	responderName: z.string(),
});
export type CheckinRequest = z.infer<typeof CheckinRequestSchema>;

export const CheckoutRequestSchema = z.object({
	vehicleId: z.string(),
});
export type CheckoutRequest = z.infer<typeof CheckoutRequestSchema>;
